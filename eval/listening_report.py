"""Pool every completed listening session and write eval/listening_results.md.

    python -m eval.listening_report

Two questions, one table per question:

  Does Speedman beat uniform at this speed?  -> forced-choice wins, two-sided sign test
  Is this speed usable at all?               -> how often the content could be followed

Ties ("no difference") are excluded from the sign test rather than split, which is the
standard treatment: a listener who cannot hear a difference provides no evidence either
way, and splitting ties would manufacture significance from indifference.
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

from . import listening
from .sweep import _sign_test_p

RESULTS_MD = Path(__file__).resolve().parent / "listening_results.md"

MIN_DECISIVE = 8
"""Below this, the sign test cannot reach p < 0.05 no matter how lopsided: 7/7 is
p = 0.016 but 6/6 is p = 0.031 and 5/5 is p = 0.063, so small rungs get flagged."""


def collect() -> tuple[dict[float, dict[str, int]], list[str]]:
    pooled: dict[float, dict[str, int]] = {}
    used: list[str] = []

    for row in listening.list_sessions():
        if not row["complete"]:
            continue
        session = listening.load_session(row["session_id"])
        used.append(session.session_id)
        for entry in listening.summarise(session):
            bucket = pooled.setdefault(entry["speed"], {
                "speedman": 0, "uniform": 0, "ties": 0,
                "followed_both": 0, "followed_picked": 0, "followed_neither": 0,
            })
            for key in bucket:
                bucket[key] += entry[key]
    return pooled, used


def render(pooled: dict[float, dict[str, int]], sessions: list[str]) -> str:
    out: list[str] = [
        "# Listening Test Results",
        "",
        f"Generated by `python -m eval.listening_report` on {time.strftime('%Y-%m-%d %H:%M')}.",
        "",
        f"Pooled from {len(sessions)} completed session(s): {', '.join(sessions) or 'none'}.",
        "",
        "Forced choice between Speedman and a uniform stretch to the same duration, same "
        "clip, order randomised, condition hidden until the session ended. This is the only "
        "instrument that reaches 5-6x -- ASR saturates above 3.5x and the modulation metric "
        "structurally favours uniform. See `docs/EVALUATION.md`.",
        "",
    ]

    if not pooled:
        out += ["No completed sessions yet. Run one from the Listening Test tab at "
                "http://127.0.0.1:8081 and re-run this report.", ""]
        return "\n".join(out)

    out += [
        "## Does Speedman beat uniform?",
        "",
        "Ties are excluded from the test rather than split -- a listener who hears no "
        "difference is evidence for neither side.",
        "",
        "| speed | Speedman | uniform | ties | decisive | p | verdict |",
        "|---|---|---|---|---|---|---|",
    ]
    for speed, c in sorted(pooled.items()):
        sm, un, ties = c["speedman"], c["uniform"], c["ties"]
        n = sm + un
        if n == 0:
            out.append(f"| {speed:g}x | 0 | 0 | {ties} | 0 | -- | no decisive trials |")
            continue
        p = _sign_test_p(sm, n)
        if n < MIN_DECISIVE:
            verdict = f"too few trials (need {MIN_DECISIVE}+)"
        elif p >= 0.05:
            verdict = "no difference detected"
        elif sm > un:
            verdict = "**Speedman wins**"
        else:
            verdict = "**uniform wins**"
        out.append(f"| {speed:g}x | {sm} | {un} | {ties} | {n} | {p:.4f} | {verdict} |")
    out.append("")

    out += [
        "## Where does speech stop being usable?",
        "",
        "'Followed' counts trials where the listener could follow the content either way. "
        "The ceiling is the speed at which this collapses.",
        "",
        "| speed | followed both | only the one picked | neither | followable rate |",
        "|---|---|---|---|---|",
    ]
    for speed, c in sorted(pooled.items()):
        both, picked, neither = c["followed_both"], c["followed_picked"], c["followed_neither"]
        total = both + picked + neither
        rate = f"{100 * (both + picked) / total:.0f}%" if total else "--"
        out.append(f"| {speed:g}x | {both} | {picked} | {neither} | {rate} |")
    out += [
        "",
        "## Limits",
        "",
        "- **One listener.** A real result for them, not a generalisable one.",
        "- **The sign test detects only large effects at this scale.** 20 decisive trials "
        "need ~15 wins for p < 0.05.",
        "- **Content repeats across rungs** when the clip pool is small. Trial order is "
        "randomised so practice effects spread evenly rather than favouring one speed, but "
        "they are not removed. Expanding `eval/manifest.py` is the fix.",
        "",
    ]
    return "\n".join(out)


def main(argv=None) -> int:
    pooled, sessions = collect()
    text = render(pooled, sessions)
    RESULTS_MD.write_text(text, encoding="utf-8")
    print(text)
    print(f"\nwrote {RESULTS_MD.relative_to(RESULTS_MD.parent.parent)}")
    if not pooled:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
